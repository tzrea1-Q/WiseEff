export function evaluateSelfHostEnv(env: Record<string, string | undefined>): IpLabPreflightResult {
  const profile = (env.WISEEFF_DEPLOY_PROFILE ?? "").trim();
  if (profile === acmeDeployProfile) {
    return evaluateAcmeEnv(env);
  }
  return evaluateIpLabEnv(env);
}

function evaluateAcmeEnv(env: Record<string, string | undefined>): IpLabPreflightResult {
  const issues: IpLabPreflightResult["issues"] = [];
  const requireValue = (key: string) => {
    const value = env[key]?.trim();
    if (!value) {
      issues.push({ level: "error", message: `${key} is required for the ACME profile.` });
    }
    return value;
  };

  if ((env.WISEEFF_DEPLOY_PROFILE ?? "").trim() !== acmeDeployProfile) {
    issues.push({ level: "error", message: "WISEEFF_DEPLOY_PROFILE must be acme." });
  }
  if ((env.WISEEFF_TLS_MODE ?? "").trim() !== "acme") {
    issues.push({ level: "error", message: "WISEEFF_TLS_MODE must be acme." });
  }
  if ((env.WISEEFF_CADDYFILE ?? "").trim() !== acmeCaddyfile) {
    issues.push({ level: "error", message: `WISEEFF_CADDYFILE must be ${acmeCaddyfile}.` });
  }
  if ((env.NODE_ENV ?? "").trim() !== "production") {
    issues.push({ level: "error", message: "NODE_ENV must be production." });
  }
  if ((env.AUTH_PROVIDER ?? "").trim() !== "local") {
    issues.push({
      level: "error",
      message: "AUTH_PROVIDER must be local for wizard-managed ACME v1. OIDC is out of this wizard."
    });
  }

  const host = requireValue("WISEEFF_SITE_HOST");
  const email = requireValue("WISEEFF_TLS_EMAIL");
  if (email && !email.includes("@")) {
    issues.push({ level: "error", message: "WISEEFF_TLS_EMAIL must be an email address." });
  }
  const publicUrl = requireValue("WISEEFF_PUBLIC_URL");
  if (host && publicUrl) {
    const expected = publicUrlForSelfHost(host, "acme");
    if (publicUrl !== expected) {
      issues.push({
        level: "error",
        message: `WISEEFF_PUBLIC_URL must be ${expected} for host ${host}.`
      });
    }
  }
  for (const key of ["WISEEFF_API_BASE_URL", "VITE_WISEEFF_API_BASE_URL", "DEVICE_BRIDGE_SERVER_URL"] as const) {
    const value = env[key]?.trim();
    if (publicUrl && value && value !== publicUrl) {
      issues.push({ level: "error", message: `${key} must match WISEEFF_PUBLIC_URL.` });
    }
  }

  const postgresPassword = requireValue("POSTGRES_PASSWORD");
  if (postgresPassword && !urlSafeSecretPattern.test(postgresPassword)) {
    issues.push({
      level: "error",
      message: "POSTGRES_PASSWORD must be URL-safe ([A-Za-z0-9_-]) so DATABASE_URL stays valid."
    });
  }
  const databaseUrl = requireValue("DATABASE_URL");
  if (databaseUrl?.includes("${")) {
    issues.push({ level: "error", message: "DATABASE_URL must embed the expanded POSTGRES_PASSWORD." });
  } else if (postgresPassword && databaseUrl && !databaseUrl.includes(postgresPassword)) {
    issues.push({ level: "error", message: "DATABASE_URL must embed the expanded POSTGRES_PASSWORD." });
  }

  requireValue("WISEEFF_LAB_ADMIN_USERNAME");
  const adminPassword = requireValue("WISEEFF_LAB_ADMIN_PASSWORD");
  if (adminPassword && adminPassword.length < 8) {
    issues.push({ level: "error", message: "WISEEFF_LAB_ADMIN_PASSWORD must be at least 8 characters." });
  }

  const xiaozeReady =
    (env.XIAOZE_DETERMINISTIC ?? "").trim() === "true" ||
    Boolean(env.AGENT_API_BASE_URL?.trim() && env.AGENT_API_KEY?.trim());
  if (!xiaozeReady) {
    issues.push({
      level: "error",
      message: "Set XIAOZE_DETERMINISTIC=true or provide AGENT_API_BASE_URL and AGENT_API_KEY."
    });
  }
  const logAnalysisReady =
    (env.LOG_ANALYSIS_DETERMINISTIC ?? "").trim() === "true" ||
    Boolean(env.LOG_ANALYSIS_API_BASE_URL?.trim() && env.LOG_ANALYSIS_API_KEY?.trim());
  if (!logAnalysisReady) {
    issues.push({
      level: "error",
      message:
        "Set LOG_ANALYSIS_DETERMINISTIC=true or provide LOG_ANALYSIS_API_BASE_URL and LOG_ANALYSIS_API_KEY."
    });
  }

  if ((env.LOG_ANALYSIS_QUEUE_MODE ?? "").trim() !== "durable") {
    issues.push({ level: "error", message: "LOG_ANALYSIS_QUEUE_MODE must be durable." });
  }
  requireValue("REDIS_URL");

  return {
    status: issues.some((issue) => issue.level === "error") ? "failed" : "passed",
    issues
  };
}

export function evaluateSelfHostCaddyfile(text: string, tlsMode: SelfHostTlsMode) {
  if (tlsMode === "acme") {
    const normalized = text.replace(/\r\n/g, "\n").replace(/[ \t]+/g, " ").trim();
    const missingTokens = requiredAcmeCaddyTokens.filter((token) => !normalized.includes(token));
    return {
      status: missingTokens.length === 0 ? "passed" : "failed",
      missingTokens,
      forbiddenTokens: [] as string[]
    };
  }
  return evaluateIpLabCaddyfile(text, tlsMode);
}

export function summarizeEnv(env: Record<string, string | undefined>) {
  return {
    profile: env.WISEEFF_DEPLOY_PROFILE?.trim() || "unknown",
    tlsMode: env.WISEEFF_TLS_MODE?.trim() || "",
    publicUrl: env.WISEEFF_PUBLIC_URL?.trim() || "",
    adminUsername: env.WISEEFF_LAB_ADMIN_USERNAME?.trim() || "",
    seed: env.WISEEFF_LAB_SEED?.trim() || "chargelab",
    llm:
      env.AGENT_API_KEY?.trim() && env.LOG_ANALYSIS_API_KEY?.trim()
        ? "xiaoze+logs"
        : env.AGENT_API_KEY?.trim()
          ? "xiaoze"
          : "skip"
  };
}

