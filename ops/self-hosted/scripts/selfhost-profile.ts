export const acmeDeployProfile = "acme";
export const acmeCaddyfile = "Caddyfile.example";

export const requiredAcmeCaddyTokens = [
  "email {$WISEEFF_TLS_EMAIL}",
  "tls {$WISEEFF_TLS_EMAIL}",
  "reverse_proxy api:8787",
  "reverse_proxy web:5173",
  "handle /api/*",
  "handle /health/*"
] as const;

const urlSafeSecretPattern = /^[A-Za-z0-9_-]+$/;

export function publicUrlForSelfHost(host: string, tlsMode: SelfHostTlsMode) {
  if (tlsMode === "acme") {
    return `https://${formatHostForUrl(host)}`;
  }
  return publicUrlForLab(host, tlsMode);
}

export function caddyfileForSelfHost(tlsMode: SelfHostTlsMode) {
  if (tlsMode === "acme") {
    return acmeCaddyfile;
  }
  return caddyfileForTlsMode(tlsMode);
}

export function resolveSecrets(
  existing: Record<string, string | undefined> | undefined,
  force: boolean,
  generate = generateUrlSafeSecret
): SelfHostSecrets {
  const postgresPassword = existing?.POSTGRES_PASSWORD?.trim();
  const minioPassword = existing?.MINIO_ROOT_PASSWORD?.trim();
  if (!force && postgresPassword && minioPassword) {
    return { postgresPassword, minioPassword };
  }
  return {
    postgresPassword: generate(),
    minioPassword: generate()
  };
}

export function renderSelfHostEnv(answers: SelfHostAnswers, secrets: SelfHostSecrets) {
  const normalized = normalizeAnswers(answers);
  if (normalized.profile === "ip-lab") {
    return renderIpLabEnv({
      host: normalized.siteHost,
      tlsMode: normalized.tlsMode as IpLabTlsMode,
      adminUsername: normalized.adminUsername,
      adminPassword: normalized.adminPassword,
      adminName: normalized.adminName,
      seed: normalized.seed,
      postgresPassword: secrets.postgresPassword,
      minioPassword: secrets.minioPassword,
      agentApiBaseUrl: normalized.agentApiBaseUrl,
      agentModel: normalized.agentModel,
      agentApiKey: normalized.agentApiKey,
      logAnalysisApiBaseUrl: normalized.logAnalysisApiBaseUrl,
      logAnalysisModel: normalized.logAnalysisModel,
      logAnalysisApiKey: normalized.logAnalysisApiKey
    });
  }
  return renderAcmeEnv(normalized, secrets);
}

