import * as XLSX from "xlsx";
import { IMPORT_TEMPLATE_HEADERS } from "./columnMap";

export function buildImportTemplateWorkbook(): Uint8Array {
  const workbook = XLSX.utils.book_new();
  const sheet = XLSX.utils.aoa_to_sheet([[...IMPORT_TEMPLATE_HEADERS]]);
  const widths = [28, 24, 48, 24, 24, 12, 12, 32, 48, 16, 16].map((wch) => ({ wch }));
  sheet["!cols"] = widths;
  XLSX.utils.book_append_sheet(workbook, sheet, "参数");

  const instructions = XLSX.utils.aoa_to_sheet([
    ["项目值批量导入：填写说明", "请先阅读本页，再填写第一张“参数”表。"],
    ["用途", "为目标项目已有参数暂存新值；不能用此模板新建或修订目录定义。"],
    ["交给智能体的任务", "依据用户资料填写“参数”表，交付 .xlsx 文件；不要输出 Markdown 表格或 CSV。"],
    ["必须提供的资料", "目标项目、已有参数的准确名称和模块、用户明确要求导入的新值。"],
    ["还需确认", "参数来源是 JSON 还是 DTS，以及该参数允许的值格式；从已有配置或用户资料确认。"],
    ["资料缺失时", "必需信息不足先追问；可选信息未知留空，不猜测数值、单位、范围或模块。"],
    ["虚构示例", "“填写示例”页只演示格式。不得将示例名称或数值当作用户资料直接导入。"],
    ["输出位置", "第一张表必须是“参数”；第 1 行保留原表头，从第 2 行起每行填写一个参数。"],
    ["输出结构", "不增删或改名表头，不合并单元格，不在数据表添加标题、说明、合计或公式。"],
    ["只读取第一张表", "“填写说明”和“填写示例”不参与导入；不要将这两张表移到第一位。"],
    ["文本保真", "单元格按文本保存，避免 Excel 将前导零、长数字、日期样式或科学计数法改写。"],
    ["JSON 值", 'JSON 来源填写合法 JSON 文本，例如 3200、true、"0007"、[1,2]。保留双引号和转义。'],
    ["DTS 值", 'DTS 来源填写对应属性的值，例如 <3200> 或 "文本"；不要填写整份配置文件。'],
    ["空白和空值", "空单元格表示未提供，首尾空白会被去除；不要用空白、- 或 — 代替未知的新值。"],
    ["JSON 空值", '确需空字符串时填写 JSON 文本 ""；确需 null 时填写 null，且已有定义必须允许。'],
    ["参数名称（必填）", "填写目标项目中已有参数的准确名称；缺失名称的整行不会被导入。"],
    ["模块（必填）", "填写已有参数所属模块，照抄项目中的名称；同名同模块的参数不要重复填写。"],
    ["当前值（优先填写）", "这里填写本次希望导入的新值；与推荐值至少填写一项。"],
    ["推荐值（可选）", "仅当前值未填时，才作为本次导入值。建议新值只填当前值，推荐值留空。"],
    ["值优先级", "两列都填时，实际暂存当前值；两列均未提供时应先补齐资料，不生成该行。"],
    ["范围（可选）", "已有资料中的范围说明，例如 0–5000；不通过此列修改目录定义的数值边界。"],
    ["单位（可选）", "使用已有资料中的单位，例如 mA；不自行换算单位或猜测。"],
    ["重要性（可选）", "填写高、中、低；也接受 High/Medium/Low 或 high/medium/low，不接受数字等级。"],
    ["描述（可选）", "参数用途的一句话简介。"],
    ["说明（可选）", "补充资料中已有的使用条件、注意事项或解释；可在一个单元格内换行。"],
    ["配置格式（可选）", "填写 json 或 dts，必须与目标参数的实际来源一致；不是 integer、int32 等值类型。"],
    ["值类型（可选）", "仅填写 scalar/标量 或 complex/复杂；不是 integer、string、boolean。"],
    ["值类型含义", "单个数值、字符串或布尔值填 scalar；数组、对象等结构化值填 complex。"],
    ["字段边界", "这些辅助信息不会修订已发布的定义；新值仍须满足现有参数定义和来源格式。"],
    ["交付前检查", "名称、模块来自目标项目；每行有明确新值；无虚构示例、重复行、公式或未知占位值。"],
    ["导入步骤", "在“项目值批量导入”选择目标项目，上传文件并核对解析、匹配与预览。"],
    ["生效边界", "导入只暂存草稿；仍需由人提交并审核。不要声称生成文件就已导入或已生效。"],
  ]);
  instructions["!cols"] = [{ wch: 30 }, { wch: 120 }];
  XLSX.utils.book_append_sheet(workbook, instructions, "填写说明");

  const examples = XLSX.utils.aoa_to_sheet([
    ["以下均为虚构示例，只演示格式，请勿直接导入。实际数据请填写到第一张“参数”表。"],
    [...IMPORT_TEMPLATE_HEADERS],
    ["示例电流上限", "示例充电管理", "3200", "", "0–5000", "mA", "高", "示例电流限制", "仅演示数字值写法", "json", "scalar"],
    ["示例设备配置", "示例设备管理", '{"code":"0007","limits":[3200,4500]}', "", "", "", "中", "示例结构化配置", "JSON 内的 0007 是字符串，保留前导零", "json", "complex"],
  ]);
  examples["!cols"] = widths;
  XLSX.utils.book_append_sheet(workbook, examples, "填写示例");
  return new Uint8Array(XLSX.write(workbook, { type: "array", bookType: "xlsx" }));
}
