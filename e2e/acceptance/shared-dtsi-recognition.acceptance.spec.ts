test("#1431 retains source recognition loading, retry and empty states and a scrollable compact draft editor",async({page,catalogAcceptanceRuntime},testInfo)=>{
  void catalogAcceptanceRuntime;
  await page.setViewportSize({width:1440,height:900});
  await signInCatalogActor(page,"org-admin","/parameter-admin/sources");await dismissXiaozeHint(page);
  const created=await catalogJson(page.request,"POST","/api/v2/shared-dtsi",{data:{name:"无 compatible 的源码",sourceName:"empty.dtsi",content:'/ { node { status = "disabled"; }; };',changeDescription:"Empty recognition is valid source"}});
  expect(created.status).toBe(201);const resource=(created.body as {item:{resourceId:string}}).item.resourceId;
  const preview=await catalogJson(page.request,"POST",`/api/v2/shared-dtsi/${resource}/publication-preview`,{data:{expectedRevision:1}});
  const publication=await catalogJson(page.request,"POST",`/api/v2/shared-dtsi/${resource}/publications`,{data:{previewId:(preview.body as {item:{id:string}}).item.id,idempotencyKey:"t21-empty-source"}});
  expect(publication.status).toBe(201);const version=(publication.body as {item:{id:string}}).item.id;
  const path=`/parameter-admin/sources?resource=${resource}&version=${version}&tab=recognition`;
  const recognitionUrl=`**/api/v2/shared-dtsi/${resource}/versions/${version}/recognition*`;
  let release!:()=>void,entered!:()=>void;
  const gate=new Promise<void>(resolve=>{release=resolve;}),started=new Promise<void>(resolve=>{entered=resolve;});
  await page.route(recognitionUrl,async route=>{entered();await gate;await route.continue();});
  await page.goto(catalogAppUrl(path));await started;
  await expect(page.getByRole("status",{name:"正在读取固定版本的来源识别",exact:true})).toBeVisible();
  await catalogScreenshot(page,testInfo,"shared-recognition-loading-1440");release();
  await expect(page.getByText("此固定版本没有 compatible 声明。可继续查看源码及项目配置。",{exact:true})).toBeVisible();
  await catalogScreenshot(page,testInfo,"shared-recognition-empty-1440");
  let failRecognition=true;
  await page.route(recognitionUrl,route=>failRecognition?route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:{code:"SERVICE_UNAVAILABLE",message:"来源读取暂不可用，请重试。",details:{},requestId:"t21-injected-retry"}})}):route.continue());
  await page.reload();await expect(page.getByRole("alert")).toContainText("来源读取暂不可用");
  await catalogScreenshot(page,testInfo,"shared-recognition-retry-1440");
  failRecognition=false;
  await page.getByRole("button",{name:"重试",exact:true}).click();
  await expect(page.getByText("此固定版本没有 compatible 声明。可继续查看源码及项目配置。",{exact:true})).toBeVisible();
  const draft=await catalogJson(page.request,"POST","/api/v2/shared-dtsi",{data:{name:"紧凑窗口完整编辑器",members:[{sourceName:"boards/library/long-hardware-description.dtsi",content:'#include <identity.h>\n/ { node { compatible = DRIVER_ID; }; };\n'},
    {sourceName:"include/identity.h",content:'#define DRIVER_ID "t21,layout"\n#define VOLATILE __TIME__\n'}],buildInputs:{includeSearchPaths:["include"],defines:{ENABLED:"1"}},changeDescription:"验证错误态完整编辑器、长路径和固定操作区域。"}});
  expect(draft.status).toBe(201);const draftId=(draft.body as {item:{resourceId:string}}).item.resourceId;
  await page.goto(catalogAppUrl(`/parameter-admin/sources?resource=${draftId}`));
  await expect(page.getByLabel("资源名称",{exact:true})).toHaveValue("紧凑窗口完整编辑器");
  await page.getByText("构建设置",{exact:true}).click();
  await page.getByText("引用其他共享资源",{exact:true}).click();
  await page.getByRole("button",{name:"准备发布",exact:true}).click();await page.getByRole("button",{name:"检查并预览",exact:true}).click();
  await expect(page.getByRole("alert")).toContainText("冻结");
  await page.setViewportSize({width:1280,height:800});
  await assertNoPageOverflow(page);await catalogScreenshot(page,testInfo,"shared-draft-error-before-scroll-1280");
  const editor=page.getByLabel("DTSI 源码",{exact:true});
  await editor.scrollIntoViewIfNeeded();
  await expect(editor).toBeInViewport({ratio:0.9});
  await expect(page.getByRole("button",{name:"检查并预览",exact:true})).toBeInViewport({ratio:1});
  const body=page.locator(".shared-dtsi-resource-body");
  expect(await body.evaluate(node=>node.scrollTop>0 && node.scrollHeight>node.clientHeight)).toBe(true);
  await body.evaluate(node=>{node.scrollTop=node.scrollHeight;});
  const header=await page.locator(".shared-dtsi-header--resource").boundingBox();
  const bodyBox=await body.boundingBox();
  const editorBox=await editor.boundingBox();
  const filesBox=await page.getByRole("navigation",{name:"资源文件",exact:true}).boundingBox();
  expect(header).not.toBeNull();expect(bodyBox).not.toBeNull();expect(editorBox).not.toBeNull();expect(filesBox).not.toBeNull();
  expect(editorBox!.y).toBeGreaterThanOrEqual(header!.y+header!.height);
  expect(filesBox!.y).toBeGreaterThanOrEqual(header!.y+header!.height);
  expect(editorBox!.y).toBeGreaterThanOrEqual(bodyBox!.y);
  expect(filesBox!.y).toBeGreaterThanOrEqual(bodyBox!.y);
  expect(editorBox!.y+editorBox!.height).toBeLessThanOrEqual(bodyBox!.y+bodyBox!.height);
  expect(filesBox!.y+filesBox!.height).toBeLessThanOrEqual(bodyBox!.y+bodyBox!.height);
  expect(editorBox!.x).toBeGreaterThanOrEqual(bodyBox!.x);
  expect(filesBox!.x).toBeGreaterThanOrEqual(bodyBox!.x);
  expect(editorBox!.x+editorBox!.width).toBeLessThanOrEqual(bodyBox!.x+bodyBox!.width);
  expect(filesBox!.x+filesBox!.width).toBeLessThanOrEqual(bodyBox!.x+bodyBox!.width);
  await catalogScreenshot(page,testInfo,"shared-draft-error-editor-scrolled-1280");
});
