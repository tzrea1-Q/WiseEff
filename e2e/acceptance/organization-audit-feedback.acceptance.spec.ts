import "./helpers/loadAcceptanceEnvironment";
import { randomUUID } from "node:crypto";
import { expect, test } from "playwright/test";
import { authHeadersForRole, signInBrowserAsRole } from "./helpers/bearerAuth";
import { seedAcceptanceRoleMatrix } from "./helpers/roleFixtures";
import { withPgClient } from "./helpers/database";
import { apiRoute } from "./helpers/runtime";
import { useBrowserDiagnostics } from "./helpers/browserDiagnostics";

test.use({ viewport: { width: 1440, height: 900 } });
useBrowserDiagnostics(test, { expectedApiFailures: [{ method: "GET", path: "/api/v1/audit-events", status: 503 }] });

test("keeps audit links, feedback management and copied details in the operating organization under the real platform account", async ({ page, context }, testInfo) => {
  await seedAcceptanceRoleMatrix();
  const suffix = randomUUID().slice(0, 8), org = `audit-feedback-${suffix}`, title = `组织反馈核对-${suffix}`;
  await withPgClient(async client => { await client.query("insert into organizations(id,name) values($1,'目标反馈组织')", [org]); });
  const headers = authHeadersForRole("platform-admin");
  const createFeedback = async (scope?: string) => {
    const response = await page.request.post(apiRoute(`/api/v1/product-feedback${scope ? `?organizationId=${scope}` : ""}`), { headers, data: { description: title, pageTitle: "作用域验收", pagePath: "/knowledge", feedbackType: "experience" } });
    expect(response.status(), await response.text()).toBe(201);
    return (await response.json() as { item: { id: string } }).item.id;
  };
  const homeId = await createFeedback(), targetId = await createFeedback(org);
  const audit = await page.request.post(apiRoute(`/api/v1/audit-events?organizationId=${org}`), { headers, data: { app: "product-feedback", kind: "scope-review", action: "inspect", severity: "Low", targetType: "product-feedback", targetId } });
  expect(audit.status()).toBe(201);
  const auditId = (await audit.json() as { id: string }).id;
  let failAudit = true;
  await page.route(url => url.pathname === "/api/v1/audit-events", route => failAudit ? route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { code: "INTERNAL_ERROR", message: "审计记录暂不可用" } }) }) : route.continue());
  await signInBrowserAsRole(page, "platform-admin", `/audit?organizationId=${org}&kind=scope-review`);
  await expect(page.getByLabel("当前操作组织")).toContainText("目标反馈组织");
  await expect(page.getByText("审计记录暂不可用", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("organization-audit-error-1440.png"), animations: "disabled" });
  failAudit = false; await page.getByRole("button", { name: "重试", exact: true }).click();
  await expect(page.getByRole("table", { name: "审计事件", exact: true })).toContainText(targetId);
  const search = page.getByRole("searchbox", { name: "搜索审计记录", exact: true });
  await search.fill(targetId); await search.press("Enter");
  await expect(page).toHaveURL(url => url.searchParams.get("organizationId") === org && url.searchParams.get("q") === targetId);
  await page.getByRole("button", { name: "查看", exact: true }).click();
  const detail = page.getByRole("dialog", { name: "操作证据与变更摘要", exact: true });
  await expect(detail).toContainText("目标反馈组织");
  await detail.getByText("技术追踪信息", { exact: true }).click();
  await expect(detail).toContainText(targetId);
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await detail.getByRole("button", { name: "复制链接", exact: true }).focus(); await page.keyboard.press("Enter");
  await expect(detail.getByText("事件链接已复制", { exact: true })).toBeVisible();
  const link = new URL(await page.evaluate(() => navigator.clipboard.readText()));
  expect(link.searchParams.get("organizationId")).toBe(org); expect(link.searchParams.get("eventId")).toBe(auditId);
  await page.screenshot({ path: testInfo.outputPath("organization-audit-detail-1440.png"), animations: "disabled" });
  await page.keyboard.press("Escape"); await expect(detail).toHaveCount(0);
  await signInBrowserAsRole(page, "platform-admin", `/parameter-admin/specs/identity-mapping?organizationId=${org}`);
  const history = page.getByRole("dialog", { name: "待审核事项", exact: true }).getByRole("link", { name: "处理记录", exact: true });
  await expect(history).toHaveAttribute("href", `/audit?kind=parameter-catalog-governance&organizationId=${org}`);
  await history.click(); await expect(page).toHaveURL(url => url.pathname === "/audit" && url.searchParams.get("organizationId") === org);
  await signInBrowserAsRole(page, "platform-admin", `/feedback-admin?organizationId=${org}&id=${targetId}`);
  await expect(page.getByLabel("当前操作组织")).toContainText("目标反馈组织");
  await expect(page.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "编辑", exact: true }).click();
  await page.getByRole("combobox", { name: "优先级", exact: true }).click(); await page.getByRole("option", { name: "高优先级", exact: true }).click();
  await page.getByRole("button", { name: "保存安排", exact: true }).click();
  await expect(page.getByText("处理安排已保存。", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("organization-feedback-detail-1440.png"), animations: "disabled" });
  const target = await page.request.get(apiRoute(`/api/v1/product-feedback/${targetId}?organizationId=${org}`), { headers });
  expect((await target.json() as { item: { priority: string } }).item.priority).toBe("high");
  const home = await page.request.get(apiRoute(`/api/v1/product-feedback/${homeId}`), { headers });
  expect((await home.json() as { item: { priority: string } }).item.priority).toBe("normal");
  const me = await page.request.get(apiRoute(`/api/v1/me?organizationId=${org}`), { headers });
  expect((await me.json() as { organization: { id: string } }).organization.id).toBe("org-chargelab");
  await signInBrowserAsRole(page, "platform-admin", `/feedback?organizationId=${org}&id=${targetId}`);
  await expect(page.getByRole("link", { name: "反馈详情链接", exact: true })).toHaveAttribute("href", `/feedback?id=${targetId}&organizationId=${org}`);
});
